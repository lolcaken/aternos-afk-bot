// Bundle src/* into a single self-contained index.js.
//
// Some host panels' file managers drop nested folders on upload, which breaks
// relative requires like require("./src/logger"). This inlines every local
// module into one file behind a tiny module registry, so the deployable
// artefact is index.js + settings.json and nothing else.
//
//   node build.js            -> writes index.js (single file)
//   node build.js --check    -> verify the bundle parses and loads
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const ENTRY = path.join(ROOT, "src", "main.js");
const OUTPUT = path.join(ROOT, "index.js");

// Local modules to inline, keyed by the specifier they resolve to.
const MODULES = [
  ["src/logger.js", "./src/logger.js"],
  ["src/main.js", "./main.js"],
  ["src/client/protocol.js", "./protocol.js"],
  ["src/client/nbt.js", "./nbt.js"],
  ["src/client/index.js", "./index.js"],
  ["src/bot/state.js", "./state.js"],
  ["src/bot/modules.js", "./modules.js"],
  ["src/bot/discord.js", "./discord.js"],
  ["src/bot/controller.js", "./controller.js"],
  ["src/http/render.js", "./render.js"],
  ["src/http/views.js", "./views.js"],
  ["src/http/server.js", "./server.js"],
];

function moduleId(file) {
  return path.relative(ROOT, file).replace(/\\/g, "/");
}

// Resolve a require specifier from a given source file to a module id.
// settings.json is not inlined: it is user config and must stay a real file
// beside the bundle so people can edit it without a rebuild. It is re-pointed
// at "./settings.json", which resolves next to the bundle at runtime.
const PASS_THROUGH = new Set(["settings.json"]);

function resolve(fromId, spec) {
  if (!spec.startsWith(".")) return null; // node builtin or dependency
  const dir = path.posix.dirname(fromId);
  let p = path.posix.normalize(path.posix.join(dir, spec));
  if (MODULES.some(([id]) => id === p)) return p;
  if (MODULES.some(([id]) => id === p + ".js")) return p + ".js";
  if (MODULES.some(([id]) => id === p + "/index.js")) return p + "/index.js";
  if (PASS_THROUGH.has(p)) return "./" + p; // real file, loaded from disk
  throw new Error(`cannot resolve "${spec}" from ${fromId} (looked for ${p})`);
}

const parts = [];
parts.push(`"use strict";`);
// Node builtins and third-party packages stay real requires; only our own
// modules are inlined.
parts.push(`const __external = { net: require("net"), zlib: require("zlib"), crypto: require("crypto"), events: require("events"), http: require("http"), https: require("https"), readline: require("readline"), express: require("express") };`);
parts.push(`const __cache = {};`);
parts.push(`function __req(id) {`);
parts.push(`  if (__cache[id]) return __cache[id].exports;`);
parts.push(`  const mod = { exports: {} };`);
parts.push(`  __cache[id] = mod;`);
parts.push(`  __defs[id](mod, mod.exports, __mkreq(id));`);
parts.push(`  return mod.exports;`);
parts.push(`}`);
parts.push(`function __mkreq(fromId) {`);
parts.push(`  return function (spec) {`);
parts.push(`    // Strip a leading "./" so callers can use either form.`);
parts.push(`    const key = spec.replace(/^\\.\\//, "");`);
parts.push(`    if (__defs[key]) return __req(key);`);
parts.push(`    if (__external[key]) return __external[key];`);
parts.push(`    const m = require(spec);`);
parts.push(`    return m;`);
parts.push(`  };`);
parts.push(`}`);
parts.push(`const __defs = {};`);

// Emit registry ids with a leading "./" so Node treats them as relative
// lookups into __defs rather than as bare package names.
const asSpec = (id) => (id.startsWith(".") ? id : "./" + id);

for (const [file] of MODULES) {
  const id = moduleId(file);
  let code = fs.readFileSync(path.join(ROOT, file), "utf8");
  code = code.replace(/require\((["'])(\.[^"']*)\1\)/g, (m, q, spec2) => {
    const target = resolve(id, spec2);
    return `require(${q}${asSpec(target)}${q})`;
  });
  parts.push(
    `__defs[${JSON.stringify(
      id
    )}] = function (module, exports, require) {\n${code}\n};`
  );
}

// Rewrite the entry file's requires the same way, then wrap it as a module so
// its require() calls go through the registry shim rather than Node's real one.
let entry = fs.readFileSync(ENTRY, "utf8");
entry = entry.replace(/require\((["'])(\.[^"']*)\1\)/g, (m, q, spec2) => {
  const target = resolve("src/main.js", spec2);
  return `require(${q}${asSpec(target)}${q})`;
});
parts.push(
  `__defs["src/main.js"] = function (module, exports, require) {\n${entry}\n};`
);
// Kick off the entry module last, once every definition is registered.
parts.push(`__req("src/main.js");`);

const out = `// GENERATED by build.js - do not edit.
// Single-file build of the aternos-afk-bot source tree. Edit the files under
// src/ and re-run \`node build.js\` to regenerate.
//
// Deployable as index.js + settings.json. No folder structure required,
// because some host panels drop nested folders on upload.
${parts.join("\n")}\n`;

fs.writeFileSync(OUTPUT, out, "utf8");
console.log(
  "bundled " +
    MODULES.length +
    " modules into index.js (" +
    Math.round(Buffer.byteLength(out) / 1024) +
    " KB)"
);